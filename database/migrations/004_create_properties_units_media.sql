CREATE TABLE properties (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(120) NOT NULL,
    sector VARCHAR(120) NULL,
    administration_name VARCHAR(150) NULL,
    administration_contact VARCHAR(190) NULL,
    notes TEXT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE units (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    property_id BIGINT UNSIGNED NOT NULL,
    public_key CHAR(24) NOT NULL,
    type VARCHAR(20) NOT NULL,
    code VARCHAR(80) NOT NULL,
    location_label VARCHAR(190) NULL,
    status VARCHAR(24) NOT NULL,
    is_public TINYINT(1) NOT NULL DEFAULT 0,
    monthly_price DECIMAL(12,2) NULL,
    description TEXT NULL,
    requirements TEXT NULL,
    private_notes TEXT NULL,
    unit_number VARCHAR(50) NULL,
    tower VARCHAR(80) NULL,
    floor VARCHAR(50) NULL,
    area_m2 DECIMAL(8,2) NULL,
    bedrooms SMALLINT UNSIGNED NULL,
    bathrooms DECIMAL(4,1) NULL,
    administration_fee DECIMAL(12,2) NULL,
    registry_number VARCHAR(120) NULL,
    parking_level VARCHAR(80) NULL,
    dimensions VARCHAR(120) NULL,
    vehicle_type VARCHAR(80) NULL,
    linked_apartment_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY units_public_key_unique (public_key),
    UNIQUE KEY units_property_code_unique (property_id, code),
    KEY units_property_id_index (property_id),
    KEY units_linked_apartment_id_index (linked_apartment_id),
    CONSTRAINT units_property_id_fk FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT units_linked_apartment_id_fk FOREIGN KEY (linked_apartment_id) REFERENCES units (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE unit_media (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    unit_id BIGINT UNSIGNED NOT NULL,
    type VARCHAR(20) NOT NULL,
    stored_name VARCHAR(190) NULL,
    mime_type VARCHAR(80) NULL,
    external_url VARCHAR(1000) NULL,
    sort_order INT UNSIGNED NOT NULL DEFAULT 0,
    is_cover TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY unit_media_unit_order_index (unit_id, sort_order, id),
    CONSTRAINT unit_media_unit_id_fk FOREIGN KEY (unit_id) REFERENCES units (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
