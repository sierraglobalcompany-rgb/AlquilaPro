CREATE TABLE insurance_policies (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    lease_id BIGINT UNSIGNED NOT NULL,
    provider_name VARCHAR(190) NOT NULL,
    product_name VARCHAR(190) NOT NULL,
    policy_number VARCHAR(190) NOT NULL,
    coverage_start DATE NOT NULL,
    coverage_end DATE NOT NULL,
    coverage_snapshot_json LONGTEXT NOT NULL,
    documents_json LONGTEXT NOT NULL,
    supersedes_policy_id BIGINT UNSIGNED NULL,
    internal_notes VARCHAR(1000) NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    cancelled_by_user_id BIGINT UNSIGNED NULL,
    cancelled_at DATETIME NULL,
    cancel_reason VARCHAR(500) NULL,
    PRIMARY KEY (id),
    KEY insurance_policies_lease_dates_index (lease_id, coverage_start, coverage_end),
    KEY insurance_policies_policy_number_index (policy_number),
    CONSTRAINT insurance_policies_lease_fk FOREIGN KEY (lease_id) REFERENCES leases (id) ON DELETE RESTRICT,
    CONSTRAINT insurance_policies_supersedes_fk FOREIGN KEY (supersedes_policy_id) REFERENCES insurance_policies (id) ON DELETE RESTRICT,
    CONSTRAINT insurance_policies_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT insurance_policies_cancelled_by_user_fk FOREIGN KEY (cancelled_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE insurance_claims (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    policy_id BIGINT UNSIGNED NOT NULL,
    incident_on DATE NOT NULL,
    description VARCHAR(1000) NOT NULL,
    claimed_amount DECIMAL(12,2) NULL,
    status VARCHAR(32) NOT NULL,
    radicado VARCHAR(190) NULL,
    filed_on DATE NULL,
    resolved_on DATE NULL,
    resolution_notes VARCHAR(1000) NULL,
    checklist_snapshot_json LONGTEXT NOT NULL,
    documents_json LONGTEXT NOT NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY insurance_claims_policy_status_index (policy_id, status),
    KEY insurance_claims_radicado_index (radicado),
    CONSTRAINT insurance_claims_policy_fk FOREIGN KEY (policy_id) REFERENCES insurance_policies (id) ON DELETE RESTRICT,
    CONSTRAINT insurance_claims_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
