CREATE TABLE maintenance_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    lease_id BIGINT UNSIGNED NOT NULL,
    category VARCHAR(80) NOT NULL,
    priority ENUM('low', 'medium', 'high', 'urgent') NOT NULL DEFAULT 'medium',
    description TEXT NOT NULL,
    photos_json LONGTEXT NOT NULL,
    status ENUM('open', 'in_progress', 'resolved', 'cancelled') NOT NULL DEFAULT 'open',
    assigned_user_id BIGINT UNSIGNED NULL,
    damage_classification ENUM('normal_wear', 'tenant_damage', 'owner_responsibility', 'third_party', 'not_applicable') NULL,
    resolution_notes VARCHAR(1000) NULL,
    charge_id BIGINT UNSIGNED NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    resolved_by_user_id BIGINT UNSIGNED NULL,
    resolved_at DATETIME NULL,
    cancelled_by_user_id BIGINT UNSIGNED NULL,
    cancelled_at DATETIME NULL,
    cancel_reason VARCHAR(500) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY maintenance_requests_charge_unique (charge_id),
    KEY maintenance_requests_lease_status_index (lease_id, status, created_at),
    KEY maintenance_requests_assigned_status_index (assigned_user_id, status),
    CONSTRAINT maintenance_requests_lease_fk FOREIGN KEY (lease_id) REFERENCES leases (id) ON DELETE RESTRICT,
    CONSTRAINT maintenance_requests_assigned_user_fk FOREIGN KEY (assigned_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT maintenance_requests_charge_fk FOREIGN KEY (charge_id) REFERENCES charges (id) ON DELETE RESTRICT,
    CONSTRAINT maintenance_requests_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT maintenance_requests_resolved_by_user_fk FOREIGN KEY (resolved_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT maintenance_requests_cancelled_by_user_fk FOREIGN KEY (cancelled_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
