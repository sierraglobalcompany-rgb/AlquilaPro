CREATE TABLE lease_obligations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    lease_id BIGINT UNSIGNED NOT NULL,
    type VARCHAR(32) NOT NULL,
    service_name VARCHAR(120) NULL,
    description VARCHAR(500) NOT NULL,
    period_month DATE NULL,
    issued_on DATE NULL,
    due_on DATE NULL,
    amount DECIMAL(12,2) NOT NULL,
    external_reference VARCHAR(190) NULL,
    source_support_stored_name VARCHAR(190) NULL,
    source_support_mime_type VARCHAR(80) NULL,
    source_support_sha256 CHAR(64) NULL,
    source_support_size_bytes BIGINT UNSIGNED NULL,
    settlement_support_stored_name VARCHAR(190) NULL,
    settlement_support_mime_type VARCHAR(80) NULL,
    settlement_support_sha256 CHAR(64) NULL,
    settlement_support_size_bytes BIGINT UNSIGNED NULL,
    charge_id BIGINT UNSIGNED NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    settled_by_user_id BIGINT UNSIGNED NULL,
    settled_at DATETIME NULL,
    voided_by_user_id BIGINT UNSIGNED NULL,
    voided_at DATETIME NULL,
    void_reason VARCHAR(500) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY lease_obligations_charge_unique (charge_id),
    KEY lease_obligations_lease_due_index (lease_id, due_on),
    KEY lease_obligations_lease_period_type_index (lease_id, period_month, type),
    KEY lease_obligations_created_by_user_index (created_by_user_id),
    KEY lease_obligations_settled_by_user_index (settled_by_user_id),
    KEY lease_obligations_voided_by_user_index (voided_by_user_id),
    CONSTRAINT lease_obligations_lease_fk FOREIGN KEY (lease_id) REFERENCES leases (id) ON DELETE RESTRICT,
    CONSTRAINT lease_obligations_charge_fk FOREIGN KEY (charge_id) REFERENCES charges (id) ON DELETE RESTRICT,
    CONSTRAINT lease_obligations_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT lease_obligations_settled_by_user_fk FOREIGN KEY (settled_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT lease_obligations_voided_by_user_fk FOREIGN KEY (voided_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
