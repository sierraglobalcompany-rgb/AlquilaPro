CREATE TABLE contract_templates (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(190) NOT NULL,
    document_type VARCHAR(40) NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY contract_templates_name_unique (name),
    KEY contract_templates_created_by_user_index (created_by_user_id),
    CONSTRAINT contract_templates_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE contract_template_versions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    template_id BIGINT UNSIGNED NOT NULL,
    version_number SMALLINT UNSIGNED NOT NULL,
    body_template LONGTEXT NOT NULL,
    variables_json TEXT NOT NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY contract_template_versions_template_version_unique (template_id, version_number),
    KEY contract_template_versions_created_by_user_index (created_by_user_id),
    CONSTRAINT contract_template_versions_template_fk FOREIGN KEY (template_id) REFERENCES contract_templates (id) ON DELETE RESTRICT,
    CONSTRAINT contract_template_versions_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE contracts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    candidate_id BIGINT UNSIGNED NOT NULL,
    unit_id BIGINT UNSIGNED NOT NULL,
    template_version_id BIGINT UNSIGNED NOT NULL,
    document_type VARCHAR(40) NOT NULL,
    status VARCHAR(24) NOT NULL,
    monthly_rent DECIMAL(12,2) NOT NULL,
    administration_fee DECIMAL(12,2) NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    duration_text VARCHAR(120) NOT NULL,
    manual_variables_json TEXT NULL,
    tasks_json TEXT NULL,
    annexes_json TEXT NULL,
    resolved_variables_json LONGTEXT NULL,
    snapshot_html LONGTEXT NULL,
    pdf_stored_name VARCHAR(190) NULL,
    pdf_sha256 CHAR(64) NULL,
    pdf_size_bytes BIGINT UNSIGNED NULL,
    created_by_user_id BIGINT UNSIGNED NULL,
    finalized_by_user_id BIGINT UNSIGNED NULL,
    generated_at DATETIME NULL,
    finalized_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY contracts_candidate_index (candidate_id),
    KEY contracts_unit_index (unit_id),
    KEY contracts_template_version_index (template_version_id),
    KEY contracts_status_index (status),
    KEY contracts_created_by_user_index (created_by_user_id),
    KEY contracts_finalized_by_user_index (finalized_by_user_id),
    CONSTRAINT contracts_candidate_fk FOREIGN KEY (candidate_id) REFERENCES candidates (id) ON DELETE RESTRICT,
    CONSTRAINT contracts_unit_fk FOREIGN KEY (unit_id) REFERENCES units (id) ON DELETE RESTRICT,
    CONSTRAINT contracts_template_version_fk FOREIGN KEY (template_version_id) REFERENCES contract_template_versions (id) ON DELETE RESTRICT,
    CONSTRAINT contracts_created_by_user_fk FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT contracts_finalized_by_user_fk FOREIGN KEY (finalized_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
